#!/usr/bin/env bash
# Generates Config/Version.xcconfig from the versionName of the Android app (ADR-0037): its first three numbers, because
# App Store Connect accepts no more. Run by `make vectors`; `make vectors-check` fails if the committed file differs.
# Usage: app-version.sh
set -euo pipefail

cd "$(dirname "$0")/.."
gradle=../android-src/KV4PHT/app/build.gradle
name=$(sed -nE 's/^ *versionName *"([^"]+)".*/\1/p' "$gradle")
version=$(sed -nE 's/^([0-9]+\.[0-9]+\.[0-9]+)(\.[0-9]+)*$/\1/p' <<<"$name")
if [[ -z "$version" ]]; then
  echo "app-version: no version with three numbers in \"$name\" of $gradle" >&2
  exit 1
fi
cat >Config/Version.xcconfig <<VERSION
// Generated by scripts/app-version.sh from the Android versionName $name. Do not edit.

MARKETING_VERSION = $version
VERSION
